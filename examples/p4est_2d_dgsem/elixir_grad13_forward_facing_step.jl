using OrdinaryDiffEqLowStorageRK
using Trixi
using AeroTrixi

###############################################################################
# Supersonic flow of a rarefied gas over a forward-facing step, described by Grad's
# 13-moment equations (Grad13). The setup reproduces the case `cases/ffs.txt` of the
# finite-volume solver `MultiBlockMomentsFV` (M. Torrilhon): the channel [0, 3] × [0, 1] with
# a step of height 1/3 at x = 1, an inflow with density 1, temperature 1 and velocity
# 2 √(5/3) (Mach 2 with respect to the Euler sound speed √(5/3 θ)), and specular walls.
#
# The DG discretization uses the Lax-Friedrichs flux with the wave-speed bounds of the
# finite-volume solver, shock capturing by blending with a subcell finite-volume scheme, and adaptive mesh
# refinement driven by the local deviation from equilibrium, `nonequilibrium`: the stress and
# the heat flux relative to the pressure. This measure is of the order of the Knudsen number in
# smooth flow and of order one in the shock layers, so the refinement follows the shocks and
# the shear layers of the moment solution and converges once their inner structure is resolved.
#
# The collision terms are explicit source terms. They relax the stress with the collision
# frequency ν = ρ √θ / Kn (about 1200 behind the shock at Kn = 0.005), so the time step has to
# keep ν Δt below the real-axis stability limit of the Runge-Kutta method (about 2.5) in
# addition to the CFL condition. The time step is controlled by the CFL number alone; the
# analysis output prints the maximum of ν to judge ν Δt. On the mesh below, the CFL time step
# keeps ν Δt well below 1; smaller Knudsen numbers or coarser meshes need a smaller CFL number.

Kn = 0.005
equations = Grad13Equations2D(Kn)

"""
    initial_condition_forward_facing_step(x, t, equations::Grad13Equations2D)

Uniform supersonic flow in equilibrium (no stress, no heat flux) with density 1, temperature 1,
and velocity 2 √(5/3) in x-direction. Also used as the inflow state.
"""
function initial_condition_forward_facing_step(x, t, equations::Grad13Equations2D)
    rho = 1.0
    v1 = 2 * sqrt(5 / 3)
    v2 = 0.0
    theta = 1.0
    # equilibrium: T_ij = θ δ_ij, q = 0
    return prim2cons(SVector(rho, v1, v2, theta, theta, 0.0, theta, 0.0, 0.0), equations)
end
initial_condition = initial_condition_forward_facing_step

# Lax-Friedrichs flux with the crude wave-speed bounds of the finite-volume solver. The shock
# in front of the step is a reflected shock with a relative Mach number of 3, far beyond the
# critical Mach number of Grad13, so that the moment equations are not hyperbolic inside the
# shock layer. With the less dissipative HLL flux (`flux_hll_grad13`), a density spike grows at
# the head of the shock and the run breaks down; the additional dissipation of the
# Lax-Friedrichs flux keeps the shock layer at the values of the finite-volume solution. There
# is no entropy-conservative two-point flux for Grad13, so the DG volume integral uses the
# central flux (standard DGSEM) and is blended with the subcell finite-volume scheme in
# troubled elements.
surface_flux = flux_lax_friedrichs
volume_flux = flux_central
polydeg = 2
basis = LobattoLegendreBasis(polydeg)
indicator_sc = IndicatorHennemannGassner(equations, basis,
                                         alpha_max = 0.5,
                                         alpha_min = 0.001,
                                         alpha_smooth = true,
                                         variable = density_pressure)
volume_integral = VolumeIntegralShockCapturingHG(indicator_sc;
                                                 volume_flux_dg = volume_flux,
                                                 volume_flux_fv = surface_flux)
solver = DGSEM(basis, surface_flux, volume_integral)

# Quadrilateral mesh of the step channel generated by Gmsh from `forward_facing_step.geo`,
# graded from the far field (characteristic length `meshSize`) to the face and the corner of
# the step (`meshSize / refinement`); the physical lines of the geometry name the boundaries.
# The Abaqus mesh file is generated with `gmsh` if it is missing or older than the geometry
# (when `gmsh` is available), i.e., it is updated after changes of the geometry:
#
#   gmsh -2 -o forward_facing_step.inp forward_facing_step.geo
#
# p4est then refines every quadrilateral of the Gmsh mesh uniformly `initial_refinement_level`
# times: with the default geometry (1/3 to 1/72), level 2 gives elements of 1/12 to 1/288,
# level 3 of 1/24 to 1/576, and level 4 of 1/48 to 1/1152. The shocks are born at the face of
# the step within a few time steps, where the mesh is finest.
initial_refinement_level = 2
geo_file = joinpath(@__DIR__, "forward_facing_step.geo")
mesh_file = joinpath(@__DIR__, "forward_facing_step.inp")
if !isfile(mesh_file) ||
   (mtime(geo_file) > mtime(mesh_file) && !isnothing(Sys.which("gmsh")))
    run(`gmsh -2 -o $mesh_file $geo_file`)
end
mesh = P4estMesh{2}(mesh_file, polydeg = polydeg,
                    initial_refinement_level = initial_refinement_level,
                    boundary_symbols = [:PhysicalLine1, :PhysicalLine2, :PhysicalLine3])

# Supersonic inflow by prescribing the full state, open outflow, specular walls, assigned to
# the physical lines of the Gmsh geometry by their labels
boundary_conditions = (; PhysicalLine1 = BoundaryConditionDirichlet(initial_condition), # inflow (x = 0)
                       PhysicalLine2 = boundary_condition_do_nothing, # outflow (x = 3)
                       PhysicalLine3 = boundary_condition_slip_wall) # walls and step

semi = SemidiscretizationHyperbolic(mesh, equations, initial_condition, solver;
                                    boundary_conditions,
                                    source_terms = source_terms_grad13)

###############################################################################
# ODE solvers, callbacks etc.

tspan = (0.0, 1.0)
ode = semidiscretize(semi, tspan)

summary_callback = SummaryCallback()

analysis_interval = 100
analysis_callback = AnalysisCallback(semi, interval = analysis_interval,
                                     extra_analysis_integrals = (max_collision_frequency,))

alive_callback = AliveCallback(analysis_interval = analysis_interval)

# The solution is saved in the output variables of the finite-volume solver
save_solution = SaveSolutionCallback(interval = 500,
                                     save_initial_solution = true,
                                     save_final_solution = true,
                                     solution_variables = cons2moments)

# Adaptive mesh refinement (not used in this non-adaptive setup): refine where the gas is far
# from equilibrium, the element maximum of the stress and heat flux relative to the pressure.
# The levels count from the elements of the Gmsh mesh, so `ControllerMinimumSize` stops the
# refinement at a minimum element size everywhere, in particular in the already fine elements
# at the step. To use it, uncomment the following lines and add `amr_callback` to the
# `CallbackSet` below (before the step size callbacks).
# amr_indicator = IndicatorMax(semi, variable = nonequilibrium)
# amr_controller = ControllerMinimumSize(ControllerThreeLevel(semi, amr_indicator,
#                                                             base_level = initial_refinement_level,
#                                                             med_level = initial_refinement_level + 1,
#                                                             med_threshold = 0.05,
#                                                             max_level = initial_refinement_level + 2,
#                                                             max_threshold = 0.2);
#                                        h_min = 1.05 / 288)
# amr_callback = AMRCallback(semi, amr_controller,
#                            interval = 5,
#                            adapt_initial_condition = true,
#                            adapt_initial_condition_only_refine = true)

# CFL condition of the hyperbolic part; it also has to keep the explicit relaxation stable
stepsize_callback = StepsizeCallback(cfl = 0.5)

callbacks = CallbackSet(summary_callback,
                        analysis_callback, alive_callback,
                        save_solution,
                        stepsize_callback)

###############################################################################
# run the simulation

# The expansion around the corner of the step drives the gas towards vacuum; the
# positivity-preserving limiter keeps the density and the pressure (which is concave in the
# conservative variables, as for the Euler equations) of the nodal values positive by scaling
# towards the element means
stage_limiter! = PositivityPreservingLimiterZhangShu(thresholds = (1.0e-6, 1.0e-6),
                                                     variables = (Trixi.density,
                                                                  Trixi.pressure))

sol = solve(ode, CarpenterKennedy2N54(; stage_limiter!, williamson_condition = false);
            dt = 1.0, # solve needs some value here but it will be overwritten by the stepsize callback
            ode_default_options()..., callback = callbacks);
