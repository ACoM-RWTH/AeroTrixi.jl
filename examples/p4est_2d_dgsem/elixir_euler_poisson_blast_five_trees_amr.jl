using OrdinaryDiffEqLowStorageRK
using Trixi
using AeroTrixi

# Gridap.jl is loaded without bringing all its names into scope (`solve` would clash with
# the time integration); this also loads the Gridap.jl extension of AeroTrixi.jl. Only the
# names for the weak form are imported.
import Gridap
using Gridap: ∫, ∇, ⋅
using LinearAlgebra: cholesky, Symmetric

###############################################################################
# Euler equations with an electrostatic potential φ and field E = -∇φ.
#
# The state is (ρ, ρv1, ρv2, ρe, φ, E1, E2). On each Runge-Kutta stage, the Poisson problem
# -Δφ = ρ - ρ0 is solved with continuous Q2 finite elements in Gridap.jl on the current,
# adapted mesh, and φ and E are written into the DG solution. The matrix factorization is
# reused until the mesh changes; after each mesh adaptation (and at the start), a callback
# rebuilds it and updates φ and E on the new mesh.
# The force of the field on the flow (`source_terms_electrostatic`) is switched off with
# `coupling = 0`: the potential follows the density, but does not act on the flow yet.
#
# Besides AeroTrixi.jl and Trixi.jl, this example requires the packages
# OrdinaryDiffEqLowStorageRK.jl, Gridap.jl, and LinearAlgebra in the active environment.
# The documentation page "Trixi.jl-Gridap.jl bridge" shows how to plot the results.

equations = CompressibleEulerPoissonEquations2D(1.4; coupling = 0.0)

# Background density of the Poisson problem
const RHO_0 = 1.0

"""
    initial_condition_blast_pressure(x, t, equations::CompressibleEulerPoissonEquations2D)

Circular blast wave with constant density `RHO_0` and zero velocity: the pressure is 2
inside the radius 0.3 and 1 outside.
The density, and with it the potential, is only generated by the evolving blast wave.
The potential and the field are initially zero and set by the Poisson callback.
"""
function initial_condition_blast_pressure(x, t,
                                          equations::CompressibleEulerPoissonEquations2D)
    r = sqrt(x[1]^2 + x[2]^2)
    p = r > 0.3 ? 1.0 : 2.0
    return prim2cons(SVector(RHO_0, 0.0, 0.0, p, 0.0, 0.0, 0.0), equations)
end
initial_condition = initial_condition_blast_pressure

# DG with polydeg = 2: the DG nodes of each element coincide with its Q2 nodes
surface_flux = flux_lax_friedrichs
volume_flux = flux_ranocha
basis = LobattoLegendreBasis(2)
indicator_sc = IndicatorHennemannGassner(equations, basis,
                                         alpha_max = 0.5,
                                         alpha_min = 0.001,
                                         alpha_smooth = true,
                                         variable = density_pressure)
volume_integral = VolumeIntegralShockCapturingHG(indicator_sc;
                                                 volume_flux_dg = volume_flux,
                                                 volume_flux_fv = surface_flux)
solver = DGSEM(basis, surface_flux, volume_integral)

# Five blocks with 2 × 2 trees each and a center square of half-width l = 0.4
mesh = p4est_mesh_five_trees(l = 0.4, trees_per_block = 2, polydeg = 2,
                             initial_refinement_level = 1)

# Open boundaries for the flow
boundary_conditions = (; x_neg = boundary_condition_do_nothing,
                       x_pos = boundary_condition_do_nothing,
                       y_neg = boundary_condition_do_nothing,
                       y_pos = boundary_condition_do_nothing)

semi = SemidiscretizationHyperbolic(mesh, equations, initial_condition, solver;
                                    boundary_conditions,
                                    source_terms = source_terms_electrostatic)

###############################################################################
# ODE solvers, callbacks etc.

tspan = (0.0, 0.3)
ode = semidiscretize(semi, tspan)

summary_callback = SummaryCallback()

analysis_interval = 100
analysis_callback = AnalysisCallback(semi, interval = analysis_interval)

alive_callback = AliveCallback(analysis_interval = analysis_interval)

save_solution = SaveSolutionCallback(interval = 100,
                                     save_initial_solution = true,
                                     save_final_solution = true,
                                     solution_variables = cons2prim)

amr_indicator = IndicatorHennemannGassner(semi,
                                          alpha_max = 0.5,
                                          alpha_min = 0.001,
                                          alpha_smooth = true,
                                          variable = density_pressure)
# Low thresholds refine a wide region around the shock, so that the mesh only needs to be
# adapted every 20 steps; each adaptation also rebuilds the finite element data
amr_controller = ControllerThreeLevel(semi, amr_indicator,
                                      base_level = 1,
                                      med_level = 3, med_threshold = 0.015,
                                      max_level = 5, max_threshold = 0.05)
amr_callback = AMRCallback(semi, amr_controller,
                           interval = 20,
                           adapt_initial_condition = true,
                           adapt_initial_condition_only_refine = true)

# Poisson problem -Δφ = ρ - ρ0 with φ = 0 on all sides of the box, in weak form
# ∫ ∇v ⋅ ∇φ = ∫ v (ρ - ρ0). The matrix is symmetric positive definite, also with the
# hanging-node constraints.
poisson_problem = GridapLinearProblem((φ, v, dΩ) -> ∫(∇(v) ⋅ ∇(φ)) * dΩ,
                                      (v, sources, dΩ) -> ∫(v * sources[1]) * dΩ;
                                      factorize = A -> cholesky(Symmetric(A)))
# The source ρ - ρ0 is transferred from the DG solution; `write_electrostatic` sets the
# variables φ, E1, E2 of the DG solution
poisson_callback = GridapCallback(semi, poisson_problem;
                                  source = (u, x, equations) -> SVector(u[1] - RHO_0),
                                  write = write_electrostatic,
                                  dirichlet_tags = (:x_neg, :x_pos, :y_neg, :y_pos))
# Solve the Poisson problem on each Runge-Kutta stage, called by the time integration method
# as `stage_limiter!`; the callback then only acts after mesh changes
poisson_stage_update = gridap_stage_update(poisson_callback)

stepsize_callback = StepsizeCallback(cfl = 0.9)

# The Poisson callback comes after the AMR callback, so that φ and E are recomputed on the
# new mesh before the next step
callbacks = CallbackSet(summary_callback,
                        analysis_callback, alive_callback,
                        amr_callback, poisson_callback,
                        save_solution,
                        stepsize_callback)

###############################################################################
# run the simulation

# The stage limiter is only called with `williamson_condition = false`
sol = solve(ode,
            CarpenterKennedy2N54(; stage_limiter! = poisson_stage_update,
                                 williamson_condition = false);
            dt = 1, # solve needs some value here but it will be overwritten by the stepsize_callback
            ode_default_options()..., callback = callbacks);
