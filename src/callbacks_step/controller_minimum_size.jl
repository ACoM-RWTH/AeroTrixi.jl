@muladd begin
#! format: noindent

"""
    ControllerMinimumSize(controller; h_min)

Wrap an AMR `controller` (such as `ControllerThreeLevel`) so that elements whose size is
already at most `h_min` are never refined further. The size of an element is the square root
of its area.

The refinement levels of the AMR controllers count from the root elements of the mesh. On a
graded mesh, for instance one generated by Gmsh with a finer characteristic length around a
geometric feature, the root elements have very different sizes, and the same maximum level
means very different element sizes. With this wrapper, the levels of `controller` set the
resolution of the coarse part of the mesh, while `h_min` bounds the resolution everywhere.
Coarsening is not affected.
"""
struct ControllerMinimumSize{Controller, RealT <: Real}
    controller :: Controller
    h_min      :: RealT
end

function ControllerMinimumSize(controller; h_min)
    return ControllerMinimumSize{typeof(controller), typeof(h_min)}(controller, h_min)
end

function Base.show(io::IO, controller::ControllerMinimumSize)
    @nospecialize controller # reduce precompilation time

    print(io, "ControllerMinimumSize(")
    print(io, controller.controller)
    print(io, ", h_min=", controller.h_min, ")")
    return nothing
end

function Base.show(io::IO, mime::MIME"text/plain", controller::ControllerMinimumSize)
    @nospecialize controller # reduce precompilation time

    if get(io, :compact, false)
        show(io, controller)
    else
        summary_header(io, "ControllerMinimumSize")
        summary_line(io, "h_min", controller.h_min)
        summary_line(io, "controller", controller.controller |> typeof |> nameof)
        show(increment_indent(io), mime, controller.controller)
        summary_footer(io)
    end
    return nothing
end

# forward the element variables (the indicator values) of the wrapped controller
function get_element_variables!(element_variables, u, mesh, equations, solver, cache,
                                controller::ControllerMinimumSize, amr_callback;
                                kwargs...)
    return get_element_variables!(element_variables, u, mesh, equations, solver, cache,
                                  controller.controller, amr_callback; kwargs...)
end

max_level(controller::ControllerMinimumSize) = max_level(controller.controller)

# Trixi.jl reads the levels and the indicator of the controller of an `AMRCallback` directly
# as fields (e.g., `print_level_information` of the `AnalysisCallback`); forward them to the
# wrapped controller
function Base.getproperty(controller::ControllerMinimumSize, name::Symbol)
    if name === :controller || name === :h_min
        return getfield(controller, name)
    else
        return getproperty(getfield(controller, :controller), name)
    end
end

function Base.propertynames(controller::ControllerMinimumSize)
    return (fieldnames(ControllerMinimumSize)...,
            propertynames(getfield(controller, :controller))...)
end

function (controller::ControllerMinimumSize)(u::AbstractArray{<:Any}, mesh, equations,
                                             dg::DG, cache; kwargs...)
    lambda = controller.controller(u, mesh, equations, dg, cache; kwargs...)

    for element in eachelement(dg, cache)
        if lambda[element] > 0 &&
           element_size(element, mesh, equations, dg, cache) <= controller.h_min
            lambda[element] = 0
        end
    end

    return lambda
end

# square root of the area of an element: the sum of the quadrature weights divided by the
# inverse Jacobian determinant
function element_size(element,
                      mesh::Union{TreeMesh{2}, StructuredMesh{2}, P4estMesh{2}},
                      equations, dg::DGSEM, cache)
    @unpack weights = dg.basis
    @unpack inverse_jacobian = cache.elements
    area = zero(real(dg))
    for j in eachnode(dg), i in eachnode(dg)
        area += weights[i] * weights[j] /
                abs(get_inverse_jacobian(inverse_jacobian, mesh,
                                         i, j, element))
    end
    return sqrt(area)
end
end # @muladd
